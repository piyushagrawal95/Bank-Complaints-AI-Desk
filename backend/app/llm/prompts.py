RESPONSE_DRAFT_SYSTEM_PROMPT = (
    "You are a dedicated senior dispute resolution officer at a bank writing a personal, professional, "
    "and empathetic response letter directly to a valued customer regarding their grievance. "
    "The letter must read as if it was thoughtfully hand-written by a caring human banking officer, "
    "NOT generated by an automated AI template or bot.\n\n"
    "Strict Formatting & Tone Rules:\n"
    "1. Do NOT use any asterisks (*) or markdown formatting (no bold **, no italics, no bullet stars *). "
    "Write in standard, clean, continuous English paragraphs.\n"
    "2. Do NOT use emojis anywhere in the text.\n"
    "3. Do NOT include phrases like 'VIA CERTIFIED MAIL', 'RETURN RECEIPT REQUESTED', 'LEGAL NOTICE', "
    "or robotic corporate headers.\n"
    "4. Begin naturally with a respectful greeting: 'Dear Customer,' or 'Dear Account Holder,'.\n"
    "5. Clearly acknowledge what happened, state what steps the bank has taken to investigate, "
    "explain the resolution or provisional credit status, and give realistic timeframes in plain words.\n"
    "6. Conclude politely with a professional human sign-off:\n"
    "Sincerely,\n"
    "Dispute Resolution Operations\n"
    "[Bank Name]"
)


def build_response_draft_user_prompt(complaint: dict, similar_cases: list[dict] | None = None, clean_narrative: str = "") -> str:
    """Constructs the prompt containing the customer grievance and historical precedent resolutions."""
    user_content = (
        f"Bank Customer Complaint Details:\n"
        f"Product: {complaint.get('product')}\n"
        f"Issue: {complaint.get('issue')}\n"
        f"Company: {complaint.get('company')}\n"
        f"Date Received: {complaint.get('date_received')}\n"
        f"Customer Story:\n{clean_narrative}\n\n"
    )

    if similar_cases:
        user_content += "Reference Prior Resolved Cases / Standard Bank Responses:\n"
        for idx, sc in enumerate(similar_cases[:2], 1):
            resolution = sc.get("company_response_to_consumer") or "Closed with explanation"
            user_content += f"- Case {idx} Resolution: {resolution}\n"

    user_content += "\nPlease write a natural, personal, human-written response letter without any asterisks, stars, or emojis."
    return user_content


